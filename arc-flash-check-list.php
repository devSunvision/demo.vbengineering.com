<h1 class="page-title">What is Arc Flash ?</h1>
<div class="separator-2"></div>
<!-- page-title end -->
<div class="row">
<div class="col-md-6">
<div class="row">
<div class="col-md-6">
<img src="img16/pages/arc-flash-check-list1.jpg" alt="arc-flash-consultants" title="arc-flash-analysis"/>
</div>
<div class="col-md-6">
<p align="justify">Arc Flash is the result of a rapid release of energy due to an Arcing fault between a phase bus bar and another phase bus bar, neutral or a ground and here air is the conductor. Arc faults are generally limited to systems where the bus voltage is in excess of 120 volts.</p>
</div>
</div>
<p align="justify">Lower voltage levels normally will not sustain an Arc. An Arc fault is similar to the Arc obtained during electric welding and the fault has to be manually started by something creating the path of conduction or a failure such as a breakdown in insulation. Are your employees and equipment at risk? Following is an abbreviated checklist for Arc Flash safety. The checklist is based on information found in the IEEE “Guide for Maintenance, Operation, and Safety of Industrial and Commercial Power Systems (Yellow Book). If you answer “no” or “Don’t know” to any of these questions, you should review your Arc Flash safety program immediately. You may be non-compliant with industry safety standards and at risk for an Arc Flash incident.</p>
